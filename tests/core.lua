-- Run with NVIM_APPNAME=nvim-bean from this directory.
local ok, err = pcall(function()
  local root = vim.fn.stdpath("config")
  assert(vim.fn.filereadable(root .. "/init.lua") == 1, "Create the standalone Bean init.lua")
  dofile(root .. "/init.lua")
  assert(vim.g.colors_name == "bean", "Use the original Bean colours")
  assert(package.loaded["lazy"] == nil and package.loaded["lazyvim"] == nil, "Do not load LazyVim or lazy.nvim")
  assert(vim.fn.exists(":RecentFiles") == 2 and vim.fn.exists(":Ghost") == 2, "Keep recent and quiet-mode commands")
  assert(vim.fn.maparg("<leader>e", "n"):find("Oil", 1, true), "Keep Space e for Oil")
  assert(vim.fn.maparg("<leader>f", "n", false, true).desc == "Find files (Bean buffer)", "Keep the full-window finder")
  assert(vim.fn.maparg("<leader>/", "n", false, true).desc == "Search contents (Bean buffer)", "Space / must search project contents")
  assert(vim.fn.maparg("<leader>r", "n", false, true).desc == "Recent files (Bean buffer)", "Keep recent-file shortcut")
  assert(vim.fn.maparg(" ", "n") == "<Nop>", "Space is a leader prefix, never a right motion")
  assert(vim.fn.maparg("<leader>a", "n", false, true).desc == "Harpoon Add File", "Keep Harpoon add")
  assert(vim.fn.maparg("<leader>h", "n", false, true).desc == "Harpoon Menu", "Keep Harpoon menu")
  assert(vim.fn.maparg("<Up>", "n") == "<Nop>", "Preserve arrow-key policy")
  assert(vim.o.showtabline == 0, "Do not introduce a tab/buffer bar")
  local cmp = require("blink.cmp.config")
  vim.cmd.Ghost()
  assert(require("config.ghost").enabled() and not cmp.enabled(), "Ghost mode disables completion")
  vim.cmd.Ghost()
  assert(not require("config.ghost").enabled() and cmp.enabled(), "Ghost mode restores completion")
  local old = vim.api.nvim_get_current_buf()
  require("config.recent_files").open()
  vim.fn.maparg("<Esc>", "n", false, true).callback()
  assert(vim.api.nvim_get_current_buf() == old, "Esc returns from recent files")
end)
if not ok then
  io.stderr:write(tostring(err) .. "\n")
  vim.cmd("cquit 1")
end
print("PASS standalone Bean core: theme, no Lazy, commands, keys, quiet mode and return")
vim.cmd("qa!")
